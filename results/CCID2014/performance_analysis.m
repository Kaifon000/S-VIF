function [SRCC,KRCC,PLCC,RMSE] = performance_analysis(mos,objectiveValues)
p = plot(objectiveValues,mos,'+');
set(p,'Color','blue','LineWidth',1);
beta(1) = max(mos);
beta(2) = min(mos);
beta(3) = mean(objectiveValues);
beta(4) = 0.1;
beta(5) = 0.1;
[bayta ehat,J] = nlinfit(objectiveValues,mos,@logistic,beta);
[ypre junk] = nlpredci(@logistic,objectiveValues,bayta,ehat,J);
RMSE = sqrt(sum((ypre - mos).^2) / length(mos));
PLCC = corr(mos, ypre, 'type','Pearson');
KRCC = corr(mos, objectiveValues, 'type', 'kendall');
SRCC = corr(mos, objectiveValues, 'type', 'spearman');
KRCC = abs(KRCC);
SRCC = abs(SRCC);
t = min(objectiveValues):0.01:max(objectiveValues);
[ypre junk] = nlpredci(@logistic,t,bayta,ehat,J);
hold on;
p = plot(t,ypre);
set(p,'Color','red','LineWidth',2);
xlabel('Predicted Score');
ylabel('MOS');